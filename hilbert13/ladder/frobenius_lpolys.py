"""Frobenius on the isogeny factors of Jac(C): E_15, E_21, S, A (Chapter 7, §7.9) [X].

Jac(C) ~ A^10 x E_15^15 x E_21^21 x S^35 (Chevalley-Weil, Ch. 1), with
    E_15 = C/A5 (A5 fixing two letters),  E_21 = C/L2(5) (transitive on six letters),  S ~ Jac(C/(3^2:4)),
    Jac(C/(7:3)) ~ A x E_15 x E_21 x S      (every rho in {10, 10b, 15, 21, 35} has a one-dimensional (7:3)-fixed space).
The curves are Galois closures of GPT's septic Belyi map (§6.5, side_checks.py D6)
    beta = 1 - q(z)/r,   q' = z^3 (z - 1)(z^2 - s z + t),   s = 1 +- 4 sqrt21/21,  t = 2s/3 - 10/21,
    r = -128 (51 s - 65)/1750329,   disc(beta - T) = -7 r^-6 T^2 (T - 1)^4,
branched over T = 0 (2^2 1^3), T = 1 (4 2 1), T = oo (7).  The two signs are the two curves (classes {0, 1}, {12, 14}).

Over F_p with 21 and -7 squares (p prime to 2520 and to the bad primes of the model) the Galois closure of beta has
arithmetic monodromy A7 (the discriminant is a square), so every C/H is defined over F_p.  Points of C/H over F_Q,
Q = p^k, are counted fibre by fibre:
  * T unramified: the Frobenius class is read off from the factorisation pattern of q(z) - r (1 - T) over F_Q, and the
    fibre contributes the permutation character pi_H(Frob_T) = #fixed points on H\\A7 (constant on S7-classes, since
    every H used is normalised by an odd permutation; checked);
  * T = 0, 1, oo: the local Galois group is generated by inertia sigma and the Frobenius lift phi fixing a chosen root
    (T - T_b)^(1/E).  Both act on the seven Puiseux branches z = r + c (T - T_b)^(1/e) + ..., (c^e = 1/a, where
    beta - T_b ~ a (z - r)^e): sigma(r, c) = (r, zeta_e c), phi(r, c) = (r^p, c^p).  Rational points of C/H over T_b are
    the <sigma>-orbits on H\\A7 (right action) stable under phi^k.
Checks: the genus-0 quotients C/A6, C/S5, C/L2(7) have exactly Q + 1 points; Weil bounds; the derived L-polynomial
of A has all roots on |x| = sqrt(Q) and factors over Q(sqrt-7) as L(10) L(10b).

From the L-polynomials (exact integers):
  * E_15 and E_21: a_p; CM excluded by two ordinary primes with different fields Q(sqrt(a^2 - 4p));
    E_15 and E_21 not isogenous over C by a prime where these fields differ;
  * S and A have no elliptic isogeny factor over C: at one good prime, no Frobenius eigenvalue alpha has
    [Q(alpha^k) : Q] <= 2 for any k (equivalently: the Weil polynomial has no factor of degree <= 2 after any base
    change; tested via cyclotomic ratios alpha_i/alpha_j).

Usage: python3 frobenius_lpolys.py [p ...]
"""
import sys, itertools
import flint
import sympy as sp
from a7 import A7, E, mul, inv, cyc, cycle_type, generated



# ---------------------------------------------------------------------------------------------- group data
def subgroup(*gens):
    return frozenset(generated(list(gens)))


H_LIST = {
    "A6": subgroup(cyc((0, 1, 2)), cyc((1, 2, 3, 4, 5))),
    "S5": subgroup(cyc((0, 1, 2)), cyc((0, 1, 2, 3, 4)), cyc((0, 1), (5, 6))),
    "L2(7)": subgroup(cyc((0, 1, 2, 3, 4, 5, 6)), cyc((1, 2, 4), (3, 6, 5)), cyc((1, 3), (2, 6))),
    "A5": subgroup(cyc((0, 1, 2)), cyc((0, 1, 2, 3, 4))),                      # fixes 5, 6:  E_15
    "L2(5)": subgroup(cyc((0, 1, 2, 3, 4)), cyc((0, 5), (1, 4))),              # transitive on 0..5:  E_21
    "3^2:4": subgroup(cyc((0, 1, 2)), cyc((3, 4, 5)), cyc((0, 3, 1, 4), (2, 5))),  # S
    "7:3": subgroup(cyc((0, 1, 2, 3, 4, 5, 6)), cyc((1, 2, 4), (3, 6, 5))),   # W, genus 7
}
GENUS = {"A6": 0, "S5": 0, "L2(7)": 0, "A5": 1, "L2(5)": 1, "3^2:4": 2, "7:3": 7}
ORDERS = {"A6": 360, "S5": 120, "L2(7)": 168, "A5": 60, "L2(5)": 60, "3^2:4": 36, "7:3": 21}
for k, H in H_LIST.items():
    assert len(H) == ORDERS[k], (k, len(H))

G = list(A7)
COSETS = {}
for name, H in H_LIST.items():
    seen, reps = set(), []
    for g in G:
        if g in seen:
            continue
        cs = frozenset(mul(h, g) for h in H)                # right coset H g
        seen |= cs
        reps.append(cs)
    COSETS[name] = reps
    idx = {}
    for i, cs in enumerate(reps):
        for x in cs:
            idx[x] = i
    COSETS[name] = (reps, idx)


def pi_H(name, g):
    reps, idx = COSETS[name]
    return sum(1 for cs in reps if idx[mul(next(iter(cs)), g)] == idx[next(iter(cs))])


# permutation characters by cycle type, with the S7-stability check (equal on the two classes of 7-cycles)
PI = {}
for name in H_LIST:
    tab = {}
    for g in G:
        ct = cycle_type(g)
        v = pi_H(name, g) if ct not in tab else None
        if ct in tab:
            continue
        tab[ct] = v
    # check constancy on cycle types (in particular 7a vs 7b)
    for g in G[::7]:
        assert pi_H(name, g) == tab[cycle_type(g)], (name, g)
    PI[name] = tab


def ram_count(name, sigma, phi):
    """phi-stable <sigma>-orbits on H\\A7 (right multiplication)."""
    reps, idx = COSETS[name]
    n = len(reps)
    rep_el = [next(iter(cs)) for cs in reps]
    act = lambda perm: [idx[mul(rep_el[i], perm)] for i in range(n)]
    s_act, f_act = act(sigma), act(phi)
    orbit_id, orbits = [-1] * n, []
    for i in range(n):
        if orbit_id[i] < 0:
            O, j = [], i
            while orbit_id[j] < 0:
                orbit_id[j] = len(orbits)
                O.append(j)
                j = s_act[j]
            orbits.append(O)
    return sum(1 for O in orbits if orbit_id[f_act[O[0]]] == orbit_id[O[0]] and
               all(orbit_id[f_act[j]] == orbit_id[O[0]] for j in O))


# ---------------------------------------------------------------------------------------------- the model mod p
def legendre(a, p):
    return pow(a % p, (p - 1) // 2, p)


def model(p, sqrt21):
    inv_ = lambda x: pow(x % p, -1, p)
    s = (1 + 4 * sqrt21 * inv_(21)) % p
    t = (2 * s * inv_(3) - 10 * inv_(21)) % p
    r = (-128 * (51 * s - 65) * inv_(1750329)) % p
    qc = [0, 0, 0, 0, (-t * inv_(4)) % p, ((s + t) * inv_(5)) % p, (-(s + 1) * inv_(6)) % p, inv_(7)]  # q coefficients
    return s, t, r, qc


class Curve:
    def __init__(self, p, sign):
        self.p = p
        rt = int(sp.sqrt_mod(21, p))
        self.s, self.t, self.r, self.qc = model(p, sign * rt % p)
        assert self.r != 0
        # passport check over F_p
        Fp = flint.fq_default_ctx(p, 1)
        Pp = flint.fq_default_poly_ctx(Fp)
        q = Pp([Fp(c) for c in self.qc])
        for Tb, pat in ((0, [1, 1, 1, 2, 2]), (1, [1, 2, 4])):
            f = q - Pp([Fp(self.r * (1 - Tb))])
            mults = sorted(m for g, m in f.factor()[1] for _ in range(g.degree()))
            assert mults == pat, (p, sign, Tb, mults)
        self.ram = self.local_monodromy()

    def poly_over(self, F, T):
        P = flint.fq_default_poly_ctx(F)
        c = [F(x) for x in self.qc]
        c[0] = c[0] - F(self.r) * (F(1) - T)
        return P(c)

    def local_monodromy(self):
        """(sigma, phi) on the seven Puiseux branches at T = 0, 1, oo."""
        p = self.p
        out = {}
        for Tb in (0, 1, "oo"):
            E_ = {0: 2, 1: 4, "oo": 7}[Tb]
            m = 1
            while (p ** m - 1) % E_:
                m += 1
            for extra in itertools.count():
                mm = m * (1 + extra)
                F = flint.fq_default_ctx(p, mm)
                P = flint.fq_default_poly_ctx(F)
                zeta = self.root_of_unity(F, E_)
                q = P([F(c) for c in self.qc])
                branches = []
                ok = True
                if Tb == "oo":
                    a = F(-7) * F(self.r)                      # 1/T ~ a w^7, z = 1/w
                    cs = (P([F(0)] * 7 + [F(1)]) - P([a.inverse()])).roots()
                    if len(cs) != 7:
                        ok = False
                    else:
                        branches = [("oo", c) for c, _ in cs]
                else:
                    f = q - P([F(self.r * (1 - Tb))])
                    for root, mult in f.roots():
                        if mult == 1:
                            branches.append((root, None))
                            continue
                        # beta - T_b = -(q - q(root))/r ~ -(q^(mult)(root)/mult!) (z - root)^mult / r
                        d = q
                        for _ in range(mult):
                            d = d.derivative()
                        fact = 1
                        for j in range(2, mult + 1):
                            fact *= j
                        a = -(d(root) * F(fact).inverse()) * F(self.r).inverse()
                        cs = (P([F(0)] * mult + [F(1)]) - P([a.inverse()])).roots()
                        if len(cs) != mult:
                            ok = False
                            break
                        branches += [(root, c) for c, _ in cs]
                    if sum(1 for _ in branches) != 7:
                        ok = False
                if ok:
                    break
            idx = {b: i for i, b in enumerate(branches)}
            frob = lambda x: x ** p if x != "oo" and x is not None else x
            phi = tuple(idx[(frob(r_), frob(c))] for r_, c in branches)
            sig = []
            for r_, c in branches:
                if c is None:
                    sig.append(idx[(r_, c)])
                else:
                    e = sum(1 for b in branches if b[0] == r_)
                    sig.append(idx[(r_, c * zeta ** (E_ // e))])
            sigma = tuple(sig)
            # sanity: phi sigma phi^-1 = sigma^p, both even, sigma of the right type
            sp_ = E
            for _ in range(p % E_):
                sp_ = mul(sigma, sp_)
            assert mul(mul(phi, sigma), inv(phi)) == sp_, Tb
            assert cycle_type(sigma) == {0: (2, 2, 1, 1, 1), 1: (4, 2, 1), "oo": (7,)}[Tb], (Tb, cycle_type(sigma))
            assert sigma in set(A7) and phi in set(A7), ("not in A7", Tb)
            out[Tb] = (sigma, phi)
        return out

    @staticmethod
    def root_of_unity(F, n):
        """a primitive n-th root of unity in F (n | |F*|)."""
        P = flint.fq_default_poly_ctx(F)
        cyclo = {2: [1, 1], 4: [1, 0, 1], 7: [1, 1, 1, 1, 1, 1, 1]}[n]
        return P([F(c) for c in cyclo]).roots()[0][0]

    def counts(self, k, names):
        """#(C/H)(F_{p^k}) for H in names."""
        p = self.p
        F = flint.fq_default_ctx(p, k)
        tot = {nm: 0 for nm in names}
        for T in self.field_elements(F):
            if T == F(0) or T == F(1):
                continue
            f = self.poly_over(F, T)
            fac = f.factor()[1]
            ct = tuple(sorted((g.degree() for g, m in fac for _ in range(m)), reverse=True))
            assert sum(ct) == 7 and all(m == 1 for g, m in fac)
            for nm in names:
                tot[nm] += PI[nm][ct]
        for Tb, (sigma, phi) in self.ram.items():
            phik = E
            for _ in range(k):
                phik = mul(phi, phik)
            for nm in names:
                tot[nm] += ram_count(nm, sigma, phik)
        return tot

    @staticmethod
    def field_elements(F):
        p, k = F.characteristic(), F.degree()
        z = F.gen()
        powers = [z ** i for i in range(k)]
        for coeffs in itertools.product(range(p), repeat=k):
            yield sum((F(c) * pw for c, pw in zip(coeffs, powers)), F(0))


# ---------------------------------------------------------------------------------------------- L-polynomials
x = sp.symbols("x")


def lpoly_from_counts(Q, N, g):
    """L(T) of a genus-g curve from #C(F_{Q^k}), k = 1..g  (Newton identities + functional equation)."""
    return lpoly_from_powersums(Q, [Q ** (k + 1) + 1 - N[k] for k in range(g)], g)


def lpoly_from_powersums(Q, s, g):
    e = [sp.Integer(1)]
    for k in range(1, g + 1):
        e.append(sp.Rational(sum((-1) ** (i - 1) * e[k - i] * s[i - 1] for i in range(1, k + 1)), k))
    c = [(-1) ** k * e[k] for k in range(g + 1)]
    full = c[:g] + [c[g]] + [c[j] * Q ** (g - j) for j in range(g - 1, -1, -1)]
    assert all(v == int(v) for v in full), full
    return [int(v) for v in full]


def roots_ok(L, Q):
    P = sp.Poly(list(L), x)
    return all(abs(abs(complex(rt)) - Q ** 0.5) < 1e-6 for rt in P.nroots(n=30))


def no_cyclotomic_ratio(L, Q):
    """True if no ratio alpha_i/alpha_j (i != j) of roots of P(x) = x^{2g} L(1/x) is a root of unity.
    Computed exactly: R(y) = Res_x(P(x), P(y x)) / (y-1)^{2g} must have no cyclotomic factor."""
    P = sp.Poly(list(L), x)
    y = sp.symbols("y")
    Pyx = sp.Poly(P.as_expr().subs(x, y * x), x)
    R = sp.Poly(sp.resultant(P.as_expr(), Pyx.as_expr(), x), y)
    n = P.degree()
    R1, rem = sp.div(R, sp.Poly((y - 1) ** n, y))
    cyc = []
    for fct, mult in sp.factor_list(R1.as_expr())[1]:
        fp = sp.Poly(fct, y)
        for m in range(1, 200):
            if sp.rem(sp.Poly(y ** m - 1, y), fp).is_zero:
                cyc.append((fct, m))
                break
    return R1, rem, cyc


def power_sums(L, kmax):
    """exact power sums p_1..p_kmax of the roots of the monic integer polynomial with coefficients L (Newton)."""
    c = list(L)
    ps = []
    for k in range(1, kmax + 1):
        v = -k * (c[k] if k < len(c) else 0) - sum(c[i] * ps[k - i - 1] for i in range(1, min(k, len(c))))
        ps.append(v)
    return ps


def report(p, sign):
    C = Curve(p, sign)
    c1 = C.counts(1, list(H_LIST))
    c2 = C.counts(2, ["3^2:4", "7:3", "A6", "S5", "L2(7)"])
    c3 = C.counts(3, ["7:3", "A6"])
    for nm in ("A6", "S5", "L2(7)"):
        assert c1[nm] == p + 1, (nm, c1[nm])
    assert c2["A6"] == p ** 2 + 1 and c3["A6"] == p ** 3 + 1 and c2["S5"] == p ** 2 + 1 and c2["L2(7)"] == p ** 2 + 1
    a15 = p + 1 - c1["A5"]
    a21 = p + 1 - c1["L2(5)"]
    LS = lpoly_from_counts(p, [c1["3^2:4"], c2["3^2:4"]], 2)
    # Frobenius power sums on W = C/(7:3) minus those of E15, E21, S (exact integers, Newton's identities)
    sW = [p ** k + 1 - n for k, n in ((1, c1["7:3"]), (2, c2["7:3"]), (3, c3["7:3"]))]
    s15, s21, sS = power_sums([1, -a15, p], 3), power_sums([1, -a21, p], 3), power_sums(LS, 3)
    sA = [sp.Integer(sW[k] - s15[k] - s21[k] - sS[k]) for k in range(3)]
    LA = lpoly_from_powersums(p, sA, 3)
    return dict(p=p, sign=sign, a15=a15, a21=a21, LS=LS, LA=LA, ram={k: (v[0], v[1]) for k, v in C.ram.items()})


def analyse(res):
    p = res["p"]
    lines = []
    a15, a21 = res["a15"], res["a21"]
    sqf = lambda a: sp.sign(a * a - 4 * p) * sp.prod([q for q, e in sp.factorint(abs(a * a - 4 * p)).items() if e % 2])
    lines.append(f"  a_p(E_15) = {a15:4d}  Q(sqrt({sqf(a15)}));   a_p(E_21) = {a21:4d}  Q(sqrt({sqf(a21)}))"
                 f"{'   [supersingular]' if a15 % p == 0 or a21 % p == 0 else ''}")
    LS, LA = res["LS"], res["LA"]
    lines.append(f"  L_S(T) = {LS}   roots on |x|=sqrt p: {roots_ok(LS, p)};  irreducible over Q: "
                 f"{sp.Poly(LS, x).is_irreducible}")
    lines.append(f"  L_A(T) = {LA}   roots on |x|=sqrt p: {roots_ok(LA, p)};  factors over Q(sqrt-7): "
                 f"{[sp.Poly(f, x).degree() for f, _ in sp.factor_list(sp.Poly(LA, x).as_expr(), extension=sp.sqrt(-7))[1]]}")
    for name, L in (("S", LS), ("A", LA)):
        R1, rem, cyc = no_cyclotomic_ratio(L, p)
        lines.append(f"  {name}: (y-1)^{2 * (len(L) - 1) // 2} divides Res: {rem.is_zero};  cyclotomic factors of"
                     f" Res/(y-1)^n: {[(str(f), m) for f, m in cyc] or 'none'}")
    return lines, sqf(a15), sqf(a21)


def kronecker(D, p):
    return sp.jacobi_symbol(D % p, p) if D % p else 0


def verdicts(data):
    """data: list of (p, a15, a21, LS, LA).  Exact verdicts from the finite list of primes."""
    out = []
    def fieldD(a, p):                 # squarefree part of a^2 - 4p, or None if supersingular
        if a % p == 0:
            return None
        D = a * a - 4 * p
        return int(sp.sign(D) * sp.prod([q for q, e in sp.factorint(abs(D)).items() if e % 2]))
    for name, col in (("E_15", 1), ("E_21", 2)):
        ords = [(r[0], fieldD(r[col], r[0])) for r in data if fieldD(r[col], r[0]) is not None]
        sss = [r[0] for r in data if fieldD(r[col], r[0]) is None]
        nonCM = len({D for _, D in ords}) >= 2 or any(kronecker(D, q) == 1 for _, D in ords for q in sss)
        out.append(f"  {name}: ordinary fields {[(p, D) for p, D in ords]}, supersingular at {sss}  ->  no CM: {nonCM}")
    noniso = []
    for r in data:
        D15, D21 = fieldD(r[1], r[0]), fieldD(r[2], r[0])
        if (D15 is None) != (D21 is None) or (D15 is not None and D21 is not None and D15 != D21):
            noniso.append(r[0])
    out.append(f"  E_15, E_21 not isogenous over C (different Frobenius type or field) at p in {noniso}: {bool(noniso)}")
    for nm, col in (("S", 3), ("A", 4)):
        good = []
        for r in data:
            L = r[col]
            irr = all(sp.Poly(f, x).degree() >= 3 for f, _ in sp.factor_list(sp.Poly(L, x).as_expr())[1])
            R1, rem, cyc = no_cyclotomic_ratio(L, r[0])
            if irr and rem.is_zero and not cyc:
                good.append(r[0])
        out.append(f"  {nm}: Q-irreducible factors of degree >= 3 and no root ratio a root of unity at p in {good}"
                   f"  ->  no elliptic isogeny factor over C: {bool(good)}")
    return out


